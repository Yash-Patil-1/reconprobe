# Passive test payloads to trigger WAF (SQL injection patterns)
ACTIVE_PAYLOADS = [
    "' OR '1'='1",
    "' UNION SELECT * FROM users--",
    "<script>alert(1)</script>",
    "../../../etc/passwd",
    "1 UNION SELECT password FROM admin--",
    "'; DROP TABLE users--",
    "1 AND 1=1 UNION SELECT 1,2,3--",
]


# ── Passive Detection ──────────────────────────────────────────────────────


async def detect_passive(
    url: str,
    timeout: float = 10.0,
    proxy_url: Optional[str] = None,
) -> WafResult:
    """Passively detect WAF by analyzing response headers and cookies.

    Makes a normal request and checks for WAF-specific headers and cookies.
    """
    result = WafResult(url=url)

    client_kwargs: dict = {
        "verify": False,
        "timeout": httpx.Timeout(timeout),
        "follow_redirects": True,
    }
    if proxy_url:
        client_kwargs["proxies"] = proxy_url

    try:
        async with httpx.AsyncClient(**client_kwargs) as client:
            resp = await client.get(url, headers={
                "User-Agent": (
                    "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
                    "(KHTML, like Gecko) Chrome/125.0.0.0 Safari/537.36"
                ),
            })

            headers_lower = {k.lower(): v for k, v in resp.headers.items()}
            body_lower = resp.text.lower()
            cookies = dict(resp.cookies)

            for sig in WAF_SIGNATURES:
                matched_passive = False
                matched_reasons: list[str] = []

                # Check header patterns
                for header_key, patterns in sig.header_patterns.items():
                    if header_key in headers_lower:
                        header_val = headers_lower[header_key]
                        for pattern in patterns:
                            if re.search(pattern, header_val, re.I):
                                matched_passive = True
                                matched_reasons.append(f"header:{header_key}={header_val[:50]}")
                                break

                # Check cookie patterns
                for cookie_pattern in sig.cookie_patterns:
                    for cookie_name in cookies:
                        if re.search(cookie_pattern, cookie_name, re.I):
                            matched_passive = True
                            matched_reasons.append(f"cookie:{cookie_name}")
                            break

                # Check body patterns (passive)
                for body_pattern in sig.body_patterns:
                    if body_pattern.lower() in body_lower:
                        matched_passive = True
                        matched_reasons.append(f"body matched: {body_pattern[:40]}")
                        break

                if matched_passive:
                    result.is_protected = True
                    result.passive_matches.extend(matched_reasons)
                    result.detected_wafs.append({
                        "name": sig.name,
                        "vendor": sig.vendor,
                        "description": sig.description,
                        "match_type": "passive",
                        "reason": ", ".join(matched_reasons),
                    })

    except (httpx.TimeoutException, httpx.ConnectError, httpx.HTTPError) as e:
        result.error = str(e)
    except Exception as e:
        result.error = str(e)

    return result


# ── Active Detection ────────────────────────────────────────────────────────


async def detect_active(
    url: str,
    matched_signatures: Optional[list[WafSignature]] = None,
    timeout: float = 10.0,
    proxy_url: Optional[str] = None,
) -> WafResult:
    """Actively probe for WAF by sending malicious payloads.

    Only checks signatures that were matched in passive detection
    (or all signatures if none were passively matched).

    Args:
        url: Target URL.
        matched_signatures: Signatures already matched passively (to narrow active checks).
        timeout: Request timeout.
        proxy_url: Optional proxy URL.

    Returns:
        WafResult with active confirmation data.
    """
    result = WafResult(url=url)
    signatures = matched_signatures or WAF_SIGNATURES

    if not signatures:
        return result

    client_kwargs: dict = {
        "verify": False,
        "timeout": httpx.Timeout(timeout),
        "follow_redirects": False,
    }
    if proxy_url:
        client_kwargs["proxies"] = proxy_url

    async with httpx.AsyncClient(**client_kwargs) as client:
        for payload in ACTIVE_PAYLOADS:
            try:
                # Send request with the malicious payload as a query param
                response = await client.get(
                    url,
                    params={"q": payload, "id": payload, "search": payload},
                    headers={
                        "User-Agent": f"'{payload}",
                        "Accept": "text/html,*/*",
                    },
                )

                status = response.status_code
                body = response.text.lower()

                for sig in signatures:
                    # Check if blocked status matches
                    if status in sig.block_status_codes:
                        # Check block body patterns
                        for block_pattern in sig.block_body_patterns:
                            if block_pattern.lower() in body:
                                if sig.name not in result.active_confirmed:
                                    result.active_confirmed.append(sig.name)
                                    result.is_protected = True
                                    result.detected_wafs.append({
                                        "name": sig.name,
                                        "vendor": sig.vendor,
                                        "description": sig.description,
                                        "match_type": "active",
                                        "reason": f"blocked with status {status}, matched '{block_pattern}'",
                                    })
                                break
            except (httpx.TimeoutException, httpx.HTTPError):
                continue
            except Exception:
                continue

    return result


# ── Main Orchestrator ───────────────────────────────────────────────────────


async def detect_waf(
    urls: list[str],
    enable_active: bool = True,
    proxy_url: Optional[str] = None,
    max_concurrent: int = 5,
) -> WafReport:
    """Detect WAFs protecting a list of URLs.

    Two-phase detection:
    1. Passive: analyze response headers/cookies/body for WAF signatures
    2. Active: send malicious payloads to confirm WAF behavior

    Args:
        urls: List of URLs to check.
        enable_active: Whether to perform active probing (default: True).
        proxy_url: Optional proxy URL.
        max_concurrent: Maximum concurrent requests.

    Returns:
        WafReport with detection results.
    """
    report = WafReport()
    semaphore = asyncio.Semaphore(max_concurrent)

    async def detect_one(url: str) -> WafResult:
        async with semaphore:
            # Phase 1: Passive detection
            passive_result = await detect_passive(url, proxy_url=proxy_url)
            report.total_urls_checked += 1
            if passive_result.is_protected:
                report.total_protected += 1

            # Phase 2: Active detection (optional)
            if enable_active and passive_result.is_protected:
                # Get signatures that matched passively for targeted active checks
                matched_names = {w["name"] for w in passive_result.detected_wafs}
                matched_sigs = [s for s in WAF_SIGNATURES if s.name in matched_names]
                active_result = await detect_active(
                    url, matched_signatures=matched_sigs, proxy_url=proxy_url,
                )
                # Merge active results
                passive_result.active_confirmed = active_result.active_confirmed
                for waf in active_result.detected_wafs:
                    if waf["name"] not in {w["name"] for w in passive_result.detected_wafs}:
                        passive_result.detected_wafs.append(waf)
                    passive_result.is_protected = True

            elif enable_active and not passive_result.is_protected:
                # No passive match — try broad active detection
                active_result = await detect_active(url, proxy_url=proxy_url)
                if active_result.is_protected:
                    passive_result.is_protected = True
                    passive_result.detected_wafs = active_result.detected_wafs
                    passive_result.active_confirmed = active_result.active_confirmed

            return passive_result

    tasks = [detect_one(url) for url in urls]
    results = await asyncio.gather(*tasks, return_exceptions=True)

    for i, url in enumerate(urls):
        result_val = results[i]
        if isinstance(result_val, WafResult):
            report.results[url] = result_val
        else:
            report.results[url] = WafResult(url=url, error=str(result_val) if isinstance(result_val, Exception) else None)

    return report
