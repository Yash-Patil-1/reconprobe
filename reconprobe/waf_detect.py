"""WAF (Web Application Firewall) detection and fingerprinting module.

Identifies WAFs protecting web applications using:
- Passive detection: analyzing response headers and cookies
- Active detection: sending malicious payloads to trigger WAF blocks
- Fingerprinting: matching responses against known WAF signatures

Supports 20+ WAF vendors including Cloudflare, AWS WAF, ModSecurity,
Akamai, Imperva, F5 BIG-IP, and more.
"""

from __future__ import annotations

import asyncio
import re
from dataclasses import dataclass, field
from typing import Optional

import httpx


# ── Data structures ──────────────────────────────────────────────────────────


@dataclass
class WafSignature:
    """Signature for identifying a specific WAF."""
    name: str
    vendor: str = ""
    description: str = ""
    # Passive: response header patterns
    header_patterns: dict[str, list[str]] = field(default_factory=dict)
    # Passive: cookie patterns
    cookie_patterns: list[str] = field(default_factory=list)
    # Passive: response body patterns
    body_patterns: list[str] = field(default_factory=list)
    # Active: status code when malicious request is blocked
    block_status_codes: list[int] = field(default_factory=lambda: [403, 406, 429, 503])
    # Active: body patterns in blocked response
    block_body_patterns: list[str] = field(default_factory=list)


@dataclass
class WafResult:
    """Result of WAF detection for a single URL."""
    url: str
    detected_wafs: list[dict] = field(default_factory=list)
    passive_matches: list[str] = field(default_factory=list)
    active_confirmed: list[str] = field(default_factory=list)
    is_protected: bool = False
    error: Optional[str] = None

    def to_dict(self) -> dict:
        return {
            "url": self.url,
            "is_protected": self.is_protected,
            "detected_wafs": self.detected_wafs,
            "passive_matches": self.passive_matches,
            "active_confirmed": self.active_confirmed,
        }


@dataclass
class WafReport:
    """Aggregated WAF detection report."""
    results: dict[str, WafResult] = field(default_factory=dict)
    total_urls_checked: int = 0
    total_protected: int = 0

    def to_dict(self) -> dict:
        return {
            "total_urls_checked": self.total_urls_checked,
            "total_protected": self.total_protected,
            "results": {
                url: r.to_dict() for url, r in self.results.items()
            },
        }


